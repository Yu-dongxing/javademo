package com.demo03_1105;
public class demo03_7 {
        public static void main(String[] args) {
            double fahrenheit = 80; // 华氏温度
            double celsius = (5.0 / 9.0) * (fahrenheit - 32); // 转换为摄氏温度
            // 显示华氏温度和摄氏温度
            System.out.println("华氏温度: " + fahrenheit + "°F");
            System.out.println("摄氏温度: " + celsius + "°C");
        }
    }
