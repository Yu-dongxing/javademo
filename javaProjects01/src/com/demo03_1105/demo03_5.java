package com.demo03_1105;

public class demo03_5{
    public static void main(String[] args) {
        // 整数除法，结果向下取整
        int result1 = 10 / 3;
        System.out.println("10 / 3 的结果是: " + result1);
        // 整数除法，结果向下取整
        int result2 = 10 / 5;
        System.out.println("10 / 5 的结果是: " + result2);
        // 整数取余
        int result3 = 10 % 2;
        System.out.println("10 % 2 的结果是: " + result3);
        // 浮点数取余
        double result4 = 10.5 % 3;
        System.out.println("10.5 % 3 的结果是: " + result4);
    }
}
